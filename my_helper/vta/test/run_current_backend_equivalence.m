end

function move_existing_to_trash(path, trashRoot)
if ~isfile(path)
    return;
end
mh_vta_move_path_to_trash(path, 'TrashRoot', trashRoot);
end

function path = first_existing_file(candidates)
matching = candidates(cellfun(@isfile, candidates));
if numel(matching) ~= 1
    error('run_current_backend_equivalence:InvalidExistingRun', ...
        'Expected exactly one existing E-field path from: %s', ...
        strjoin(candidates, ', '));
end
path = matching{1};
end

function path = resolve_candidate_root(runRoot, caseId)
candidates = { ...
    fullfile(runRoot, 'outputs', 'canonical', caseId), ...
    fullfile(runRoot, 'outputs', 'simbio_onesolve', caseId)};
for index = 1:numel(candidates)
    if isfolder(candidates{index})
        path = candidates{index};
        return;
    end
end
error('run_current_backend_equivalence:InvalidExistingRun', ...
    'Existing canonical candidate directory is missing for %s.', caseId);
end

