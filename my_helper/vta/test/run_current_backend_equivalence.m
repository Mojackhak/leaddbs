        'Canonical one-solve must reuse the standard SimBio headmodel.');
end
output = struct( ...
    'native', must_be_file(status.native_efield, ...
        'canonical native E-field'), ...
    'mni', must_be_file(status.mni_efield, ...
        'canonical MNI E-field'));
end

function [efieldRows, binaryRows, repeatRows, passed] = ...
        compare_all_outputs(cases, outputs)
efieldRows = table();
binaryRows = table();
repeatRows = table();
passed = true;
spaces = {'native'};
for caseIndex = 1:numel(cases)
    oneCase = cases(caseIndex);
    caseField = matlab.lang.makeValidName(oneCase.case_id);
    standard = outputs.(caseField).simbio;
    canonical = outputs.(caseField).canonical;
    for spaceIndex = 1:numel(spaces)
        space = spaces{spaceIndex};
        comparison = mh_compare_single_source_backend_outputs( ...
            standard.(space), canonical.(space), ...
            'Space', space, ...
            'Side', oneCase.hemisphere, ...
            'Comparison', 'equivalence', ...
            'ResampleCandidateToReference', false, ...
            'ThrowOnFailure', false);
        efield = annotate_rows(comparison.efield_row, oneCase.case_id, ...
            'backend');
        binary = annotate_rows(comparison.binary_rows, oneCase.case_id, ...
            'backend');
        efieldRows = [efieldRows; efield]; %#ok<AGROW>
        binaryRows = [binaryRows; binary]; %#ok<AGROW>
        passed = passed && comparison.pass;
    end
end
if ~isempty(efieldRows)
    repeatRows = efieldRows([],:);
end
end

function result = validate_candidate_mni(cases, outputs, runRoot, manifest, ...
        studyBasePath, trashRoot, repeatFunction)
thresholds = [180, 200, 220];
rows = table();
passed = true;
for caseIndex = 1:numel(cases)
    oneCase = cases(caseIndex);
    caseField = matlab.lang.makeValidName(oneCase.case_id);
    candidate = outputs.(caseField).canonical;
    repeatPath = fullfile(runRoot, 'mni_transform_repeat', ...
        [oneCase.case_id, '.nii.gz']);
    if isfile(repeatPath)
        mh_vta_move_path_to_trash(repeatPath, 'TrashRoot', trashRoot);
    end
    context = struct( ...
        'manifest', manifest, ...
        'study_base_path', char(string(studyBasePath)), ...
        'case', oneCase);
    repeatFunction(candidate.native, candidate.mni, repeatPath, context);
    mniLeaf = fileparts(candidate.mni);
    thresholdPaths = threshold_artifact_paths(mniLeaf, thresholds);
    validation = mh_validate_canonical_mni_outputs( ...
        candidate.mni, repeatPath, thresholdPaths, thresholds, ...
        'ThrowOnFailure', false);
    thresholdPass = all(validation.threshold_rows.pass);
    row = table(string(oneCase.case_id), ...
        validation.dimensions_match, validation.affine_match, ...
        validation.finite_mask_match, validation.finite_nonzero_signal, ...
        validation.deterministic_repeat, thresholdPass, validation.pass, ...
        'VariableNames', {'case_id', 'dimensions_match', 'affine_match', ...
            'finite_mask_match', 'finite_nonzero_signal', ...
            'deterministic_repeat', 'thresholds_match', 'pass'});
    rows = [rows; row]; %#ok<AGROW>
    passed = passed && validation.pass;
end
result = struct('rows', rows, 'pass', passed);
end

function generate_mni_repeat(nativePath, ~, repeatPath, context)
manifest = context.manifest;
studyDocument = jsondecode(fileread(must_be_file( ...
    context.study_base_path, 'study-base JSON')));
subject = select_subject(studyDocument, manifest.subject_id);
copiedSubject = must_be_folder(manifest.copied_subject, ...
    'copied Lead-DBS subject directory');
sourceReconstruction = char(string( ...
    subject.subject_sources.electrode_reconstruction.path));
[~, reconstructionName, reconstructionExtension] = ...
    fileparts(sourceReconstruction);
reconstructionPath = must_be_file(fullfile(copiedSubject, ...
    'reconstruction', [reconstructionName, reconstructionExtension]), ...
    'copied electrode reconstruction');
options = ea_getptopts(copiedSubject, struct());
options.subj.recon.recon = reconstructionPath;
mniReference = fullfile(ea_space(options), 't1.nii');
parent = fileparts(repeatPath);
if ~isfolder(parent)
    mkdir(parent);
end
mh_vta_transform_efield_to_mni(nativePath, options, mniReference, repeatPath);
end

function paths = threshold_artifact_paths(leaf, thresholds)
paths = cell(1, numel(thresholds));
for index = 1:numel(thresholds)
    token = strrep(sprintf('%.2f', thresholds(index) / 1000), '.', 'p');
    paths{index} = must_be_file(fullfile(leaf, ...
        ['vta_threshold-', token, 'Vpermm.nii.gz']), ...
        'canonical MNI threshold');
end
end

function result = compare_existing_run(runRoot, studyBasePath, trashRoot, ...
        repeatFunction)
manifestPath = fullfile(runRoot, 'validation_manifest.json');
manifest = jsondecode(fileread(must_be_file(manifestPath, ...
    'current acceptance manifest')));
required = {'subject_id', 'hemisphere', 'case_design', ...
    'planned_fem_solve_count'};
if ~all(isfield(manifest, required)) || ...
        ~strcmp(char(string(manifest.hemisphere)), 'R') || ...
        ~strcmp(char(string(manifest.case_design)), ...
            'single_cathode_case_return') || ...
        double(manifest.planned_fem_solve_count) ~= 2
    error('run_current_backend_equivalence:InvalidExistingRun', ...
        'Existing run does not satisfy the fixed current FEM contract.');
end

caseId = 'R_single_cathode_case_return';
oneCase = struct('case_id', caseId, 'hemisphere', 'R');
caseField = matlab.lang.makeValidName(caseId);
standardRoot = fullfile(runRoot, 'outputs', 'simbio', caseId);
candidateRoot = resolve_candidate_root(runRoot, caseId);
outputs.(caseField).simbio = struct( ...
    'native', first_existing_file({ ...
        fullfile(standardRoot, 'native_efield.nii'), ...
        fullfile(standardRoot, 'native_efield.nii.gz')}), ...
    'mni', first_existing_file({ ...
        fullfile(standardRoot, 'mni_efield.nii'), ...
        fullfile(standardRoot, 'mni_efield.nii.gz')}));
outputs.(caseField).canonical = struct( ...
    'native', first_existing_file({ ...
        fullfile(candidateRoot, 'native', 'efield.nii.gz'), ...
        fullfile(candidateRoot, 'native', 'efield.nii')}), ...
    'mni', first_existing_file({ ...
        fullfile(candidateRoot, 'MNI152NLin2009bAsym', 'efield.nii.gz'), ...
        fullfile(candidateRoot, 'MNI152NLin2009bAsym', 'efield.nii')}));

[efieldMetrics, binaryMetrics, repeatabilityMetrics, comparisonPass] = ...
    compare_all_outputs(oneCase, outputs);
mniContract = validate_candidate_mni(oneCase, outputs, runRoot, manifest, ...
    studyBasePath, trashRoot, repeatFunction);
comparisonPass = comparisonPass && mniContract.pass;
replace_table_safely(efieldMetrics, ...
    fullfile(runRoot, 'efield_metrics.csv'), trashRoot);
replace_table_safely(binaryMetrics, ...
    fullfile(runRoot, 'binary_vta_metrics.csv'), trashRoot);
replace_table_safely(repeatabilityMetrics, ...
    fullfile(runRoot, 'repeatability_metrics.csv'), trashRoot);
replace_table_safely(mniContract.rows, ...
    fullfile(runRoot, 'mni_transform_metrics.csv'), trashRoot);

summaryPath = fullfile(runRoot, 'acceptance_summary.json');
if isfile(summaryPath)
    summary = jsondecode(fileread(summaryPath));
else
    summary = struct();
end
productionTreeUnchanged = isfield(summary, ...
    'production_subject_tree_unchanged') && ...
    isscalar(summary.production_subject_tree_unchanged) && ...
    logical(summary.production_subject_tree_unchanged);
summary.subject_id = char(string(manifest.subject_id));
summary.case_count = 1;
summary.hemisphere = 'R';
summary.case_design = 'single_cathode_case_return';
summary.planned_fem_solve_count = 2;
actualFemSolveCounts = 2;
if isfield(summary, 'actual_fem_solve_count') && ...
        isnumeric(summary.actual_fem_solve_count) && ...
        isscalar(summary.actual_fem_solve_count) && ...
        isfinite(summary.actual_fem_solve_count) && ...
        summary.actual_fem_solve_count >= 2
    actualFemSolveCounts(end + 1) = ...
        double(summary.actual_fem_solve_count);
end
if isfield(manifest, 'accumulated_fem_solve_count') && ...
        isnumeric(manifest.accumulated_fem_solve_count) && ...
        isscalar(manifest.accumulated_fem_solve_count) && ...
        isfinite(manifest.accumulated_fem_solve_count) && ...
        manifest.accumulated_fem_solve_count >= 2
    actualFemSolveCounts(end + 1) = ...
        double(manifest.accumulated_fem_solve_count);
end
summary.actual_fem_solve_count = max(actualFemSolveCounts);
summary.comparison_fem_solve_count = 0;
summary.comparison_grid = 'standard_simbio_reference_grid';
summary.comparison_gates_passed = comparisonPass;
summary.native_equivalence_passed = all(efieldMetrics.pass) && ...
    all(binaryMetrics.pass);
summary.mni_transform_contract_passed = mniContract.pass;
summary.production_subject_tree_unchanged = productionTreeUnchanged;
summary.pass = comparisonPass && productionTreeUnchanged;
replace_json_safely(summaryPath, summary, trashRoot);

result = struct( ...
    'mode', 'compare_existing', ...
    'run_root', runRoot, ...
    'fem_solve_count', 0, ...
    'summary', summary, ...
    'pass', summary.pass);
end

function result = rerun_existing_candidate(runRoot, studyBasePath, trashRoot, ...
        repeatFunction, recoveryReason)
manifestPath = fullfile(runRoot, 'validation_manifest.json');
manifest = jsondecode(fileread(must_be_file(manifestPath, ...
    'current acceptance manifest')));
required = {'subject_id', 'seed', 'atlas_set', 'copied_subject', ...
    'source_subject', 'source_tree_sha256_before', 'fixture_sha256', ...
    'hemisphere', 'case_design', 'planned_fem_solve_count'};
if ~all(isfield(manifest, required)) || ...
        ~strcmp(char(string(manifest.hemisphere)), 'R') || ...
        ~strcmp(char(string(manifest.case_design)), ...
            'single_cathode_case_return') || ...
        double(manifest.planned_fem_solve_count) ~= 2
    error('run_current_backend_equivalence:InvalidExistingRun', ...
        'Existing run does not satisfy the fixed current recovery contract.');
end

studyDocument = jsondecode(fileread(must_be_file(studyBasePath, ...
    'study-base JSON')));
subject = select_subject(studyDocument, manifest.subject_id);
[sides, contactCounts] = subject_electrode_inventory(subject);
fixtureCases = generate_current_cases(double(manifest.seed), sides, ...
    contactCounts);
femPlan = official_fem_plan(fixtureCases);
oneCase = femPlan.cases;
if ~strcmp(fixture_hash(oneCase), char(string(manifest.fixture_sha256)))
    error('run_current_backend_equivalence:FixtureMismatch', ...
        'Regenerated current fixture does not match the existing run.');
end

copiedSubject = must_be_folder(manifest.copied_subject, ...
    'copied Lead-DBS subject directory');
sourceSubject = must_be_folder(manifest.source_subject, ...
    'production Lead-DBS subject directory');
sourceHashBeforeRecovery = directory_inventory_hash(sourceSubject);
sourceChangedSinceOriginal = ~strcmp(sourceHashBeforeRecovery, ...
    char(string(manifest.source_tree_sha256_before)));

caseId = oneCase.case_id;
standardRoot = fullfile(runRoot, 'outputs', 'simbio', caseId);
standardNative = first_existing_file({ ...
    fullfile(standardRoot, 'native_efield.nii'), ...
    fullfile(standardRoot, 'native_efield.nii.gz')});
first_existing_file({ ...
    fullfile(standardRoot, 'mni_efield.nii'), ...
    fullfile(standardRoot, 'mni_efield.nii.gz')});
candidateRoot = resolve_candidate_root(runRoot, caseId);
if ~isfolder(candidateRoot)
    error('run_current_backend_equivalence:InvalidExistingRun', ...
        'Existing candidate directory is missing: %s', candidateRoot);
end

priorAttempts = 0;
if isfield(manifest, 'recovery_attempt_count')
    priorAttempts = double(manifest.recovery_attempt_count);
end
recoveryAttempt = priorAttempts + 1;
recoveryStartedAt = timestamp_iso();
manifest.recovery_attempt_count = recoveryAttempt;
manifest.recovery_started_at = recoveryStartedAt;
manifest.recovery_completed_at = '';
manifest.source_tree_sha256_before_recovery = sourceHashBeforeRecovery;
manifest.source_tree_changed_since_original_acceptance = ...
    sourceChangedSinceOriginal;
manifest.accumulated_fem_solve_count = ...
    double(manifest.planned_fem_solve_count) + recoveryAttempt;
manifest.pass = false;
replace_json_safely(manifestPath, manifest, trashRoot);

mh_vta_move_path_to_trash(candidateRoot, 'TrashRoot', trashRoot);

execute_canonical_backend(copiedSubject, subject, oneCase, ...
    char(string(manifest.atlas_set)), runRoot, standardNative);
comparison = compare_existing_run(runRoot, studyBasePath, trashRoot, ...
    repeatFunction);

sourceHashAfterRecovery = directory_inventory_hash(sourceSubject);
productionTreeUnchanged = strcmp(sourceHashBeforeRecovery, ...
    sourceHashAfterRecovery);
summary = comparison.summary;
summary.actual_fem_solve_count = manifest.accumulated_fem_solve_count;
summary.recovery_attempt_count = recoveryAttempt;
summary.latest_recovery_fem_solve_count = 1;
summary.standard_reference_reused = true;
summary.recovery_reason = char(string(recoveryReason));
summary.production_subject_tree_changed_since_original_acceptance = ...
    sourceChangedSinceOriginal;
summary.production_subject_tree_unchanged_during_recovery = ...
    productionTreeUnchanged;
summary.production_subject_tree_unchanged = productionTreeUnchanged;
summary.pass = summary.comparison_gates_passed && productionTreeUnchanged;
replace_json_safely(fullfile(runRoot, 'acceptance_summary.json'), ...
    summary, trashRoot);

manifest.recovery_completed_at = timestamp_iso();
manifest.latest_recovery_fem_solve_count = 1;
manifest.source_tree_sha256_after_recovery = sourceHashAfterRecovery;
manifest.production_subject_tree_unchanged_during_recovery = ...
    productionTreeUnchanged;
manifest.pass = summary.pass;
replace_json_safely(manifestPath, manifest, trashRoot);

result = struct( ...
    'mode', 'rerun_candidate', ...
    'run_root', runRoot, ...
    'fem_solve_count', 1, ...
    'summary', summary, ...
    'pass', summary.pass);
if ~result.pass
    error('run_current_backend_equivalence:AcceptanceFailed', ...
        'Recovered current backend acceptance failed: %s', runRoot);
end
end

function replace_table_safely(value, path, trashRoot)
