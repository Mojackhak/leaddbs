function testCompleteStageSequencePrecedesTaskOutcome(testCase)
emit = mh_vta_make_event_emitter('run-001', 'SNr003'); %#ok<NASGU>
stages = [ ...
    "task_runtime_resolution", ...
    "subject_reconstruction_context", ...
    "headmodel_build_or_load", ...
    "active_contact_boundary", ...
    "fem_matrix_preparation", ...
    "fem_preconditioner", ...
    "fem_pcg_solve", ...
    "gradient_calculation", ...
    "electrode_removal_geometry", ...
    "native_grid_interpolation", ...
    "group_peak_composition", ...
    "threshold_generation", ...
    "native_to_mni_transform", ...
    "artifact_publication"];
output = evalc("emit('subject_ready',struct());" + ...
    "emit('task_started',struct('task_id','task-001'));" + ...
    "emit_all_stages(emit,stages);" + ...
    "emit('task_outcome',struct('task_id','task-001'," + ...
    "'status','generated','copied_artifact_count',0," + ...
    "'generated_artifact_count',1));" + ...
    "emit('subject_summary',success_summary());");
events = parse_events(output);
types = string(cellfun(@(event) event.event_type, ...
    events, 'UniformOutput', false));
outcomeIndex = find(types == "task_outcome", 1);
timingIndices = find(types == "stage_timing");

verifyEqual(testCase, numel(timingIndices), numel(stages));
verifyTrue(testCase, all(timingIndices < outcomeIndex));
verifyEqual(testCase, string(cellfun( ...
    @(event) event.stage, events(timingIndices), ...
    'UniformOutput', false)), stages);
verifyEqual(testCase, types(end), "subject_summary");
end

function emit_all_stages(emit, stages)
for stage = stages
    mh_vta_emit_stage_timing(emit, 'task', 'task-001', ...
        stage, 'executed', 0, '');
end
end

function fields = success_summary()
fields = struct( ...
    'generated', 1, ...
    'copied', 0, ...
    'skipped_existing', 0, ...
    'recovered_complete', 0, ...
    'failed', 0, ...
    'skipped_dependency', 0, ...
    'process_success', true);
end

function events = parse_events(output)
prefix = 'MH_VTA_EVENT ';
lines = splitlines(string(output));
lines = lines(startsWith(lines, prefix));
events = cell(1, numel(lines));
for lineIndex = 1:numel(lines)
    payload = extractAfter(lines(lineIndex), strlength(prefix));
    events{lineIndex} = jsondecode(payload);
end
end

