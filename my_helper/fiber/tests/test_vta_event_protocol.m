% Protocol tests for canonical VTA MATLAB stdout events.

tests = functiontests(localfunctions);
end

function setupOnce(testCase)
repoDir = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
addpath(genpath(fullfile(repoDir, 'my_helper', 'fiber')));
addpath(repoDir);
testCase.TestData.repoDir = repoDir;
end

function testEmitterProducesContiguousDecodableEvents(testCase)
emit = mh_vta_make_event_emitter('run-001', 'SNr003'); %#ok<NASGU>
output = evalc("emit('subject_ready', struct()); " + ...
    "emit('task_started', struct('task_id','task-001'));");

events = parse_events(output);
verifyEqual(testCase, cellfun(@(event) event.sequence, events), [1, 2]);
verifyEqual(testCase, string(cellfun(@(event) event.schema_version, ...
    events, 'UniformOutput', false)), ...
    ["vta_event_v1", "vta_event_v1"]);
verifyEqual(testCase, string(cellfun(@(event) event.event_type, ...
    events, 'UniformOutput', false)), ...
    ["subject_ready", "task_started"]);
verifyEqual(testCase, string(cellfun(@(event) event.run_id, ...
    events, 'UniformOutput', false)), ["run-001", "run-001"]);
verifyEqual(testCase, string(cellfun(@(event) event.subject_id, ...
    events, 'UniformOutput', false)), ["SNr003", "SNr003"]);
end

function testEmitterRejectsInvalidIdentityAndEventType(testCase)
verifyError(testCase, @() mh_vta_make_event_emitter( ...
    ["run-1", "run-2"], 'SNr003'), 'mh_vta:InvalidEventIdentity');
verifyError(testCase, @() mh_vta_make_event_emitter(1, 'SNr003'), ...
    'mh_vta:InvalidEventIdentity');
emit = mh_vta_make_event_emitter('run-001', 'SNr003');
verifyError(testCase, @() emit('unknown', struct()), ...
    'mh_vta:UnsupportedEventType');
verifyError(testCase, @() emit('subject_ready', ...
    struct('sequence', 99)), 'mh_vta:ReservedEventField');
end

function testStageTimingValidatesScopeAndStatus(testCase)
emit = mh_vta_make_event_emitter('run-001', 'SNr003');
output = evalc("mh_vta_emit_stage_timing(emit, 'subject', '', " + ...
    "'manifest_decode_validation', 'executed', 0.25, 'miss');");
events = parse_events(output);

event = events{1};
verifyEqual(testCase, string(event.scope), "subject");
verifyEqual(testCase, string(event.stage), ...
    "manifest_decode_validation");
verifyEqual(testCase, event.duration_seconds, 0.25);
verifyEqual(testCase, string(event.cache_status), "miss");
verifyFalse(testCase, isfield(event, 'task_id'));
verifyError(testCase, @() mh_vta_emit_stage_timing(emit, ...
    'task', '', 'fem_pcg_solve', 'executed', 0.1, ''), ...
    'mh_vta:InvalidTimingField');
verifyError(testCase, @() mh_vta_emit_stage_timing(emit, ...
    'subject', '', 'manifest_decode_validation', ...
    'not_applicable', 0.1, ''), ...
    'mh_vta:InvalidNotApplicableTiming');
end

function testSuccessfulRunnerEmitsCompleteOneTaskProtocol(testCase)
taskPath = write_task_fixture(fixture_task());
cleanup = onCleanup(@() delete_if_present(taskPath));

output = evalc("status = mh_vta_run_canonical_task(taskPath, " + ...
    "'SolveFunction', @successful_solve);");
events = parse_events(output);

verifyEqual(testCase, cellfun(@(event) event.sequence, events), 1:5);
verifyEqual(testCase, string(cellfun(@(event) event.event_type, ...
    events, 'UniformOutput', false)), [ ...
    "stage_timing", "subject_ready", "task_started", ...
    "task_outcome", "subject_summary"]);
verifyEqual(testCase, string(events{1}.stage), ...
    "manifest_decode_validation");
verifyEqual(testCase, string(events{4}.status), "generated");
verifyEqual(testCase, events{4}.generated_artifact_count, 8);
verifyEqual(testCase, events{5}.generated, 1);
verifyTrue(testCase, events{5}.process_success);
end

function testFailingRunnerEmitsFailureBeforeRethrow(testCase)
taskPath = write_task_fixture(fixture_task());
cleanup = onCleanup(@() delete_if_present(taskPath));

caughtError = [];
output = evalc("try, mh_vta_run_canonical_task(taskPath, " + ...
    "'SolveFunction', @failing_solve); " + ...
    "catch caughtError, end");
events = parse_events(output);

verifyEqual(testCase, string(caughtError.identifier), ...
    "test_vta:ExpectedSolveFailure");
verifyEqual(testCase, string(cellfun(@(event) event.event_type, ...
    events, 'UniformOutput', false)), [ ...
    "stage_timing", "subject_ready", "task_started", ...
    "task_outcome", "subject_summary"]);
verifyEqual(testCase, string(events{4}.status), "failed");
verifyEqual(testCase, string(events{4}.error_identifier), ...
    "test_vta:ExpectedSolveFailure");
verifyEqual(testCase, events{5}.failed, 1);
verifyFalse(testCase, events{5}.process_success);
end

