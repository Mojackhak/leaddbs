function path = write_task_fixture(task)
path = [tempname, '.json'];
write_text(path, jsonencode(task));
end

function write_text(path, content)
fid = fopen(path, 'w');
assert(fid >= 0, 'Could not create event protocol fixture.');
cleanup = onCleanup(@() fclose(fid));
fwrite(fid, content, 'char');
end

